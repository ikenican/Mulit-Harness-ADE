#!/usr/bin/env bash
# Regenerate the AUTO-MEMORY block inside the entry files that Codex, Antigravity and (without the
# plugin) Claude Code auto-load at startup.
#
# WHY: those tools auto-load STATIC FILES (AGENTS.md, .agents/rules/*, .claude/rules/*) but cannot
# run a command and inject its output the way the plugin's SessionStart hook can. So instead of
# asking them to run status.sh, we derive the current handoff INTO the files they already read.
#
# handoff.md remains the single source of truth. The block below is GENERATED - never hand-edited.
# Bundled with Agent Workbench (memory sync) and the shared-project-memory plugin; run by
# commit-handoff.sh and Workbench. Entry files tracked by the project repository are never written.

set -e
MEM="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$MEM/.." && pwd)"
cd "$REPO"

[ -f "$MEM/handoff.md" ] || exit 0

BEGIN_MARK="<!-- BEGIN AUTO-MEMORY (generated from .project-memory/handoff.md - do not edit) -->"
END_MARK="<!-- END AUTO-MEMORY -->"

BLOCK="$(mktemp)"
trap 'rm -f "$BLOCK"' EXIT

{
  printf '%s\n\n' "$BEGIN_MARK"
  printf '## Current shared memory (tier 1 - auto-generated, do not edit here)\n\n'
  printf 'You already have the current handoff below. Do NOT re-read `.project-memory/handoff.md`.\n'
  printf 'Read `STATE.md` / `DECISIONS.md` / `PROTOCOL.md` only on demand.\n'
  printf 'For the freshest copy plus a remote-drift check, run `bash .project-memory/status.sh`.\n\n'
  printf -- '---\n\n'
  cat "$MEM/handoff.md"
  printf '\n%s\n' "$END_MARK"
} > "$BLOCK"

inject() {
  local f="$1"
  [ -f "$f" ] || return 0
  # The project tracks this file itself (e.g. a team AGENTS.md): writing the handoff into it would
  # turn memory into a pending change of the project repository, so leave it alone.
  if git ls-files --error-unmatch -- "$f" >/dev/null 2>&1; then
    echo "  skipped (tracked by the project): $f"
    return 0
  fi
  if grep -qF "$BEGIN_MARK" "$f"; then
    # replace everything between the markers (inclusive) with the new block
    awk -v b="$BEGIN_MARK" -v e="$END_MARK" -v bf="$BLOCK" '
      $0 == b { while ((getline line < bf) > 0) print line; close(bf); skip=1; next }
      skip && $0 == e { skip=0; next }
      !skip { print }
    ' "$f" > "$f.spmtmp" && mv "$f.spmtmp" "$f"
  else
    printf '\n' >> "$f"
    cat "$BLOCK" >> "$f"
  fi
  echo "  synced: $f"
}

tracked() { git ls-files --error-unmatch -- "$1" >/dev/null 2>&1; }

# Claude Code loads .claude/rules/*.md at startup. With the shared-project-memory plugin its
# SessionStart hook already injects live memory and a static copy would only duplicate it, so the
# file exists only while the plugin is absent. Claude Code reads the user profile on Windows, which
# can differ from Git Bash's $HOME.
CLAUDE_ENTRY=".claude/rules/shared-memory.md"
CLAUDE_HEADER="# Shared project memory

Canonical cross-agent memory is \`.project-memory/\`; the current handoff is below.
Before finishing, apply the memory-update criteria in \`.project-memory/PROTOCOL.md\` and save with
\`bash .project-memory/commit-handoff.sh \"docs(memory): <one-line summary>\"\`.
Generated by .project-memory/sync-entry-files.sh while the shared-project-memory plugin is not
installed. Local to this clone - never commit it."
CLAUDE_PLUGINS="${CLAUDE_CONFIG_DIR:-${USERPROFILE:-$HOME}/.claude}/plugins/installed_plugins.json"
if grep -qs '"shared-project-memory@' "$CLAUDE_PLUGINS"; then
  # remove only our own file: header + generated block, nothing the user added
  if [ -f "$CLAUDE_ENTRY" ] && ! tracked "$CLAUDE_ENTRY" \
     && [ "$(awk -v b="$BEGIN_MARK" -v e="$END_MARK" '$0 == b { skip=1 } !skip { print } skip && $0 == e { skip=0 }' "$CLAUDE_ENTRY")" = "$CLAUDE_HEADER" ]; then
    rm -f "$CLAUDE_ENTRY"
    echo "  removed (the plugin injects memory): $CLAUDE_ENTRY"
  fi
elif [ ! -f "$CLAUDE_ENTRY" ] && ! tracked "$CLAUDE_ENTRY"; then
  mkdir -p "$(dirname "$CLAUDE_ENTRY")"
  printf '%s\n' "$CLAUDE_HEADER" > "$CLAUDE_ENTRY"
  EXCLUDE="$(git rev-parse --git-path info/exclude 2>/dev/null || true)"
  if [ -n "$EXCLUDE" ] && ! grep -qxF "/$CLAUDE_ENTRY" "$EXCLUDE" 2>/dev/null; then
    mkdir -p "$(dirname "$EXCLUDE")"
    printf '/%s\n' "$CLAUDE_ENTRY" >> "$EXCLUDE"
  fi
fi

inject "AGENTS.md"
inject ".agents/rules/shared-memory.md"
grep -qs '"shared-project-memory@' "$CLAUDE_PLUGINS" || inject "$CLAUDE_ENTRY"
